/*
4.1.1 SHA-1 Functions

SHA-1 uses a sequence of logical functions, f₀, f₁, …, f₇₉. Each function ft, where 0 ≤ t ≤ 79, operates on three 32-bit words x, y, and z, and produces a 32-bit word as output. The function ft(x, y, z) is defined as follows:
	•	Ch(x, y, z) = (x ∧ y) ⊕ (¬x ∧ z), for 0 ≤ t ≤ 19
	•	Parity(x, y, z) = x ⊕ y ⊕ z,     for 20 ≤ t ≤ 39
	•	Maj(x, y, z) = (x ∧ y) ⊕ (x ∧ z) ⊕ (y ∧ z), for 40 ≤ t ≤ 59
	•	Parity(x, y, z) = x ⊕ y ⊕ z,     for 60 ≤ t ≤ 79
*/
uint32_t sha1_f(uint64_t t, uint32_t x, uint32_t y, uint32_t z) {
	if((0 <= t) && (t <= 19)) {
		return ((x & y) ^ (~x & z));
	} else if((20 <= t) && (t <= 39)) {
		return (x ^ y ^ z);
	} else if((40 <= t) && (t <= 59)) {
		return ((x & y) ^ (x & z) ^ (y & z));
	} else if((60 <= t) && (t <= 79)) {
		return (x ^ y ^ z);
	}
	abort();
}

uint32_t sha1_k(uint64_t t) {
	//__builtin_bswap32
	if(0 <= t && t <= 19) {
		return (0x5a827999);
	} else if(20 <= t && t <= 39) {
		return (0x6ed9eba1);
	} else if(40 <= t && t <= 59) {
		return (0x8f1bbcdc);
	} else if(60 <= t && t <= 79) {
		return (0xca62c1d6);
	}
	abort();
}

/*
The following operations are used in the secure hash algorithm specifications:

ROTLn(x)
The rotate left (circular left shift) operation, where x is a w-bit word and n is an integer with 0 ≤ n < w, is defined by:
ROTLn(x) = (x << n) ∨ (x >> (w − n))

ROTRn(x)
The rotate right (circular right shift) operation, where x is a w-bit word and n is an integer with 0 ≤ n < w, is defined by:
ROTRn(x) = (x >> n) ∨ (x << (w − n))

*/

template<typename T,int n>
T ROTL(const T x) {
	constexpr uint64_t w = sizeof(T)*8;
	static_assert(0 <= n && n < w, "assertion failed: 0 <= n < w");
	uint32_t BE_X = __builtin_bswap32(x);
	return __builtin_bswap32((BE_X << n) | (BE_X >> (w - n)));
}

template<typename T,int n>
T ROTR(const T x) {
	constexpr uint64_t w = sizeof(T)*8;
	static_assert(0 <= n && n < w, "assertion failed: 0 <= n < w");
	uint32_t BE_X = __builtin_bswap32(x);
	return __builtin_bswap32((BE_X >> n) | (BE_X << (w - n)));
}

/*

5. PREPROCESSING
Preprocessing consists of three steps: padding the message, M (Sec. 5.1), parsing the message
into message blocks (Sec. 5.2), and setting the initial hash value, H(0) (Sec. 5.3).

5.1 Padding the Message
The purpose of this padding is to ensure that the padded message is a multiple of 512 or 1024
bits, depending on the algorithm. Padding can be inserted before hash computation begins on a
message, or at any other time during the hash computation prior to processing the block(s) that
will contain the padding.

*/

/*

5.1.1 SHA-1, SHA-224 and SHA-256

Suppose that the length of the message, M, is ℓ bits.
Append the bit “1” to the end of the message, followed by k zero bits, where k is the smallest
non-negative solution to the equation:

    ℓ + 1 + k ≡ 448 mod 512

Then append the 64-bit block that is equal to the number ℓ expressed using a binary representation.

For example, the (8-bit ASCII) message "abc" has length:

    ℓ = 3 × 8 = 24 bits

So the message is padded with a one bit, then:

    k = 448 − (ℓ + 1) = 448 − 25 = 423 zero bits

And then the 64-bit binary representation of the length (24) is appended.

The resulting 512-bit padded message becomes:

    01100001 01100010 01100011 1 0000...0000 000...011000
    [   a   ] [   b   ] [   c   ] 1 [ 423 zero bits ] [64-bit length: 000...011000]

Where:
    "a" = 0x61 = 01100001
    "b" = 0x62 = 01100010
    "c" = 0x63 = 01100011
    ℓ = 24 (in binary: 000...011000)

Thus the final message is:
    3 bytes of data + 1 '1' bit + 423 '0' bits + 64-bit length field = 512 bits total.

*/

/**
	@brief pads the message according to section 5.1.1
*/
HashBuffer PadMessage_5_1_1(const HashBuffer& M) {
	HashBuffer output(nullptr,0);

	const uint64_t ℓ = M.Size;
	const uint64_t k = 447 - (ℓ % 512);

	output.Size = (ℓ + 1 + k + 64) / 8;

	output.Data = calloc(1,output.Size);

	memcpy(output.Data,M.Data,ceil(M.Size / 8.0));
	ModifyBitInBuffer(output.Data, ℓ, 1);
	const uint64_t ℓ_BE = __builtin_bswap64(ℓ);

	memcpy(((uint8_t*)output.Data)+(output.Size-sizeof(ℓ_BE)),&ℓ_BE,sizeof(ℓ_BE));

	return output;
}

/*
5.1.2 SHA-384, SHA-512, SHA-512/224 and SHA-512/256

Suppose the length of the message M, in bits, is ℓ bits. 
Append the bit “1” to the end of the message, followed by k zero bits, where k is the smallest 
non-negative solution to the equation:

    ℓ + 1 + k ≡ 896 mod 1024

Then append the 128-bit block that is equal to the number ℓ expressed using a binary representation.

For example, the (8-bit ASCII) message "abc" has length:

    ℓ = 3 × 8 = 24 bits

So the message is padded with a one bit, then:

    k = 896 − (ℓ + 1) = 896 − 25 = 871 zero bits

And then a 128-bit binary representation of the length (24) is appended.

The resulting 1024-bit padded message becomes:

    01100001 01100010 01100011 1 0000...0000 000...011000
    [   a   ] [   b   ] [   c   ] 1 [ 871 zero bits ] [128-bit length: 000...011000]

Where:
    "a" = 0x61 = 01100001
    "b" = 0x62 = 01100010
    "c" = 0x63 = 01100011
    ℓ = 24 (in binary: 000...011000, left-padded to 128 bits)

Total:
    3 bytes of data + 1 '1' bit + 871 '0' bits + 128-bit length field = 1024 bits

The length of the padded message is now a multiple of 1024 bits.
*/

/**
	@brief pads the message according to section 5.1.2
	@note this function only supports ℓ <= 2^64 on account of most CPUs not supporting integers wider than 64 bits, this will be changed once hardware support allows for it
	@note as such, the upper 64 bits of ℓ i in the padded message will always be clear
*/
HashBuffer PadMessage_5_1_2(const HashBuffer& M) {
	HashBuffer output(nullptr,0);

	const uint64_t ℓ = M.Size;
	const uint64_t k = 895 - (ℓ % 1024);

	output.Size = (ℓ + 1 + k + 128) / 8;
	output.Data = calloc(1,output.Size);

	memcpy(output.Data,M.Data,ceil(M.Size / 8.0));
	ModifyBitInBuffer(output.Data, ℓ, 1);
	const uint64_t ℓ_BE = __builtin_bswap64(ℓ);
	memcpy((uint8_t*)output.Data+output.Size-sizeof(ℓ_BE),&ℓ_BE,sizeof(ℓ_BE));

	return output;
}

/*
5.2 Parsing the Message
The message and its padding must be parsed into N m-bit blocks.
*/

/*
5.2.1 SHA-1, SHA-224 and SHA-256

For SHA-1, SHA-224, and SHA-256, the message and its padding are parsed into N 512-bit
blocks:

    M(1), M(2), ..., M(N)

Each 512-bit message block M(i) is divided into sixteen 32-bit words, labeled as follows:

    M(i)_0, M(i)_1, M(i)_2, ..., M(i)_15

That is, the first 32 bits of message block i are denoted M(i)_0, the next 32 bits are M(i)_1, 
and so on up to M(i)_15.
*/

/*
5.2.2 SHA-384, SHA-512, SHA-512/224 and SHA-512/256

For SHA-384, SHA-512, SHA-512/224, and SHA-512/256, the message and its padding are 
parsed into N 1024-bit blocks:

    M(1), M(2), ..., M(N)

Each 1024-bit message block M(i) is divided into sixteen 64-bit words, labeled as:

    M(i)_0, M(i)_1, M(i)_2, ..., M(i)_15

That is, the first 64 bits of message block i are denoted M(i)_0, the next 64 bits are M(i)_1,
and so on up to M(i)_15.
*/

class ParsedMessage {
public:
	/**
		@brief word size in bytes, this assumes that no algorithm in the sha family will ever define a word size that isnt a multiple of 8 bits, that would be silly :3
	*/
	const uint64_t WordSize;
	void* WordData;
	ParsedMessage(uint64_t WordSize): WordSize(WordSize){}

	~ParsedMessage() {
		free(this->WordData);
	}

	class Block {
	public:
		uint8_t* words[16];
	};

	Block* Blocks;
	uint64_t BlockCount;
};

ParsedMessage ParseMessage(const HashBuffer& Message,AlgoConstants algo) {
	ParsedMessage output(algo.WordSize / 8);
	output.BlockCount = Message.Size / (algo.BlockSize / 8);
	output.Blocks = new ParsedMessage::Block[output.BlockCount];
	uint8_t* WordData = (uint8_t*)malloc(Message.Size);
	output.WordData = WordData;
	uint8_t* Data = (uint8_t*)Message.Data;
	for(uint64_t b = 0;b < output.BlockCount;b++) {
		for (uint64_t i = 0;i<16;i++) {
			output.Blocks[b].words[i] = WordData;
			WordData+=output.WordSize;
			memcpy(
				output.Blocks[b].words[i],
				Data,
				output.WordSize
			);
			Data+=output.WordSize;
		}
	}
	return output;
}

