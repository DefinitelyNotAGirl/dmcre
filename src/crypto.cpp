	const HashAlgorithm sha1([](void* Data,uint64_t DataSize) {
    	SHA1_CTX ctx;
    	uint8_t* hash = (uint8_t*)malloc(20);
    	if (!hash) abort();
    	sha1_init(&ctx);
    	sha1_update(&ctx, (const BYTE*)Data, (size_t)DataSize);
    	sha1_final(&ctx,hash);
    	return HashBuffer(hash,160/8);
	});

