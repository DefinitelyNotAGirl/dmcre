static inline void ModifyBitInBuffer(void* buf, uint64_t pos, bool value) {
	uint8_t* byte = ((uint8_t*)buf) + (pos / 8);
	uint8_t mask = 1 << (7 - (pos % 8));
	if(value) {
		*byte |= mask;
	} else {
		*byte &= ~mask;
	}
}

template<typename T>
static inline void ByteSwap(T* in, T* out) {
	uint8_t* _in = (uint8_t*)in;
	uint8_t* _out = (uint8_t*)out;
	for(uint64_t _pi = 0, _po = sizeof(T)-1;_pi<sizeof(T);_pi++,_po--) {
		_out[_po] = _in[_pi];
	}
}

